#!/usr/bin/env node
// Voice-over for the dialogue (README.md, Dialogue: Voice-over). Finds every line in story/*.js whose speaker has a
// voice (the story's `voices`): characters' lines, and the hero's lines and choices in each hero voice (m, f), and
// hands them to the voice-over skill's make_voices.py (.claude/skills/voice-over), which names each clip after a hash
// of its voice and text (a changed line or voice gets a new clip and the old one is removed), makes the missing ones,
// cuts their silence, retries ones that come back nearly silent, and writes the index. Lines with {…} in them
// change with the game and aren't voiced.
//
//   node tools/story/voice.js                              lists what is missing and what it would cost (nothing is made)
//   node tools/story/voice.js --go --tts <path>            makes the missing clips, removes unused ones, writes the index
//   node tools/story/voice.js --go --tts <p> --verify --stt <p>   ... and transcribes the new clips to check their words
//   node tools/story/voice.js --index-only                 only rewrites the index (story/<name>.voices.js)
//
// --tts / --stt: the ai-media-generation skill's openai_media.py / google_media.py (they hold their own keys; also
// read from $TTS_SCRIPT / $STT_SCRIPT). Clips go to assets/voice/<story>/<speaker>-<hash>.mp3 (mono, 64 kbit/s); the
// index story/<name>.voices.js maps "speaker|text" (the hero: "hero:m|text") to [file, seconds].
const fs = require('fs'), path = require('path'), vm = require('vm'), os = require('os'), { spawnSync } = require('child_process');
const ROOT = path.resolve(__dirname, '..', '..'), DIR = path.join(ROOT, 'story');
const TOOL = path.resolve(ROOT, '..', '..', '.claude', 'skills', 'voice-over', 'tools', 'make_voices.py');
const pass = process.argv.slice(2);   // --go, --tts, --verify, --stt, --index-only go straight to make_voices.py

const ctx = vm.createContext({});
for (const f of fs.readdirSync(DIR).filter(f => f.endsWith('.js') && !f.endsWith('.voices.js')).sort())
  vm.runInContext(fs.readFileSync(path.join(DIR, f), 'utf8'), ctx, { filename: f });
const STORIES = ctx.STORIES || {};
const plain = t => typeof t === 'string' && !/(^|[^\\]){/.test(t);

for (const key in STORIES) {
  const st = STORIES[key], vs = st.voices || {}, clips = [];
  const add = (who, text) => {   // one clip per voice the speaker has
    if (!plain(text)) return;
    const vars = who === 'hero' ? Object.entries(vs.hero || {}).map(([g, v]) => ['hero:' + g, v]) : vs[who] ? [[who, vs[who]]] : [];
    for (const [speaker, voice] of vars) clips.push({ speaker, voice, text: text.replace(/\\{/g, '{') });
  };
  const nodes = ns => { for (const n in ns || {}) for (const it of ns[n]) {
    if (it.say != null) add(it.say, it.text);
    if (it.choose) for (const o of it.choose) add('hero', o.text);
  } };
  for (const id in st.chars || {}) nodes(st.chars[id].nodes);
  for (const v of st.convs || []) nodes(v.nodes);
  const out = path.join(ROOT, 'assets', 'voice', key);
  if (!clips.length && !fs.existsSync(out)) continue;
  const lines = path.join(os.tmpdir(), 'voice-lines-' + key + '.json');
  fs.writeFileSync(lines, JSON.stringify({ clips }));
  console.log('== ' + key);
  const r = spawnSync('python3', [TOOL, '--lines', lines, '--out', out, '--index', path.join(DIR, key + '.voices.js'),
    '--prefix', 'assets/voice/' + key + '/', '--header', `Generated by tools/story/voice.js: the voice clips of story/${key}.js ("speaker|text" -> [file, seconds]).`,
    ...pass], { stdio: 'inherit' });
  fs.unlinkSync(lines);
  if (r.status) process.exit(r.status);
}
